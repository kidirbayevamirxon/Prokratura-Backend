import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class DeviceRegisterChallengeResponse(BaseModel):
    challenge: str
    challenge_token: str
    rp: Dict[str, str]
    user: Dict[str, str]
    pub_key_cred_params: List[Dict[str, Any]]
    authenticator_selection: Dict[str, str]
    timeout: int = 60000


class DeviceRegisterVerifyRequest(BaseModel):
    challenge_token: str = Field(
        ...,
        description="Signed challenge token received from registration challenge endpoint",
    )
    credential_id: str = Field(
        ..., description="Base64url credential rawId generated by the hardware chip"
    )
    client_data_json: str = Field(
        ..., description="Base64url clientDataJSON from authenticator"
    )
    attestation_object: str = Field(
        ..., description="Base64url attestationObject from authenticator"
    )
    device_name: Optional[str] = Field(
        None,
        description="Human readable device label (e.g. 'Prokuror Lenovo ThinkPad')",
    )


class DeviceLoginChallengeRequest(BaseModel):
    identifier: str = Field(..., description="Username or phone number")


class DeviceLoginChallengeResponse(BaseModel):
    challenge: str
    challenge_token: str
    credential_id: str
    rp_id: str
    user_verification: str = "required"
    timeout: int = 60000


class DeviceLoginVerifyRequest(BaseModel):
    challenge_token: str = Field(
        ..., description="Signed challenge token received from login challenge endpoint"
    )
    credential_id: str = Field(..., description="Base64url credential rawId")
    authenticator_data: str = Field(
        ..., description="Base64url authenticatorData from authenticator"
    )
    client_data_json: str = Field(
        ..., description="Base64url clientDataJSON from authenticator"
    )
    signature: str = Field(
        ..., description="Base64url cryptographic signature from authenticator"
    )


class UserDeviceInfo(BaseModel):
    id: int
    user_id: int
    device_name: Optional[str]
    credential_id: str
    is_active: bool
    registered_at: datetime.datetime
    last_login_at: Optional[datetime.datetime]

    model_config = ConfigDict(from_attributes=True)


class DeviceTransferTokenResponse(BaseModel):
    transfer_token: str
    expires_in: int = 300
    message: str


class DeviceResetResponse(BaseModel):
    message: str
    user_id: int
    status: str
